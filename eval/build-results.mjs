// Writes eval/RESULTS.md from the result folders, so every number in it comes from a file.
//
//   npm run eval:results
//   npm run eval:results -- --real eval/results/real-gemini/<folder> [--real-fix eval/results/real-gemini/<folder>]
//
// Re-run after any new experiment run (and after `npm run eval:rescore -- <folder>` for real-Gemini runs).
import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";
import { mean, ci95, parseCSV, mdTable } from "./lib/stats.mjs";

const EVAL = path.dirname(fileURLToPath(import.meta.url));
const R = (p) => path.join(EVAL, "results", p);
const { values: a } = parseArgs({
  options: {
    gate: { type: "string", default: R("gate-sim/v2-20261013") },
    "gate-fix": { type: "string", default: R("gate-sim/v2-20261013-extract-nomin") },
    retrieval: { type: "string", default: R("retrieval/v2-20261013") },
    reach: { type: "string", default: R("reachability/v2-20261013") },
    "scorer-check": { type: "string", default: R("real-scorer-check/v2-20261013") },
    real: { type: "string", default: R("real-gemini/20261013-130739") },
    "real-fix": { type: "string" },
    out: { type: "string", default: path.join(EVAL, "RESULTS.md") },
  },
});
const rel = (p) => path.relative(EVAL, p).split(path.sep).join("/");
const csv = (dir, f) => parseCSV(fs.readFileSync(path.join(dir, f), "utf8"));
const jsonl = (dir, f) => (fs.existsSync(path.join(dir, f)) ? fs.readFileSync(path.join(dir, f), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l)) : []);
const json = (dir, f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const f = (x, d = 2) => (Number.isFinite(+x) ? (+x).toFixed(d) : "n/a");
const pct = (x) => `${Math.round(100 * x)}%`;

// ---------------------------------------------------------------- data
const G = csv(a.gate, "summary.csv");
const GF = csv(a["gate-fix"], "summary.csv");
const gCfg = json(a.gate, "config.json");
const gRuns = jsonl(a.gate, "runs.jsonl");
const cell = (S, sweep, policy, e, u) => S.find((r) => r.sweep === sweep && r.policy === policy && +r.e === e && +r.u === u);
const err = (S, policy, e) => cell(S, "error", policy, e, gCfg.u);
const n = (r, k) => +r[k];
const destroyedAll = (r) => n(r, "destroyed_mean") + n(r, "fillerLost_mean");
const errors = gCfg.errors;
const POL = { append: "append", auto: "auto", gate: "gate (AURA)", gateAll: "gateAll" };

const RS = csv(a.retrieval, "summary.csv");
const TH = csv(a.retrieval, "threshold.csv");
const RQ = jsonl(a.retrieval, "queries.jsonl");
const RA = jsonl(a.retrieval, "absent.jsonl");
const rCfg = json(a.retrieval, "config.json");
const CH = csv(a.reach, "summary.csv");
const CHrows = jsonl(a.reach, "changes.jsonl");
const reachCfg = json(a.reach, "config.json");
const SC = jsonl(a["scorer-check"], "runs.jsonl");

const real = fs.existsSync(path.join(a.real, "rescored.jsonl")) ? { dir: a.real, rows: jsonl(a.real, "rescored.jsonl"), labels: jsonl(a.real, "labels.jsonl"), cfg: json(a.real, "config.json") } : null;
const realFix = a["real-fix"] && fs.existsSync(path.join(a["real-fix"], "rescored.jsonl")) ? { dir: a["real-fix"], rows: jsonl(a["real-fix"], "rescored.jsonl"), cfg: json(a["real-fix"], "config.json") } : null;

// ---------------------------------------------------------------- text
const md = [];
const P = (...x) => md.push(...x);
P(`# Results: user-controlled memory in AURA (Direction A)`, ``);
P(`Generated by \`npm run eval:results\` (eval/build-results.mjs) on ${new Date().toISOString().slice(0, 10)}; every number below is computed from the run folders named in each section. ` +
  `Do not edit numbers by hand: re-run the experiment, then this script. How the experiments work: [README.md](README.md).`, ``);
P(`**Status of the evidence.** Experiments 1-3 use AURA's real memory code, database and local embedding model (Xenova/all-MiniLM-L6-v2) with a **simulated** extractor ` +
  `and a simulated user: they measure the system's mechanics, not Gemini's judgement. ` +
  (real
    ? `Experiment 4 uses the **real** Gemini extractor (${real.cfg.extractor}) on ${real.rows.filter((r) => r.policy === real.rows[0].policy).length} personas per policy: enough to see which errors a real model makes, too few for firm rates.`
    : `Experiment 4 (real Gemini) has not been run yet.`), ``);

// Finding 1
const red = errors.filter((e) => e > 0).map((e) => 1 - destroyedAll(err(G, "gate", e)) / destroyedAll(err(G, "auto", e)));
const gatePrompts = errors.map((e) => n(err(G, "gate", e), "promptsPer100Turns_mean"));
const e2 = errors.includes(0.2) ? 0.2 : errors[Math.floor(errors.length / 2)];
const e1 = errors.includes(0.1) ? 0.1 : errors[1];
P(`## Finding 1: the review gate stops almost all destructive changes, at a cost of ${Math.round(Math.min(...gatePrompts))}-${Math.round(Math.max(...gatePrompts))} prompts per 100 turns`, ``);
P(`\`${rel(a.gate)}/\` (n = ${gCfg.personas * gCfg.seeds} personas per cell, user slip rate u = ${gCfg.u}; mean, ± = 95% CI)`, ``);
P(mdTable(["e", "policy", "F1", "stale", "false", "true facts destroyed", "prompts / 100 turns", "prompt precision"],
  errors.flatMap((e) => Object.keys(POL).map((p) => {
    const r = err(G, p, e);
    return [e, POL[p], `${f(r.f1_mean, 3)} ± ${f(r.f1_ci95, 3)}`, f(r.stale_mean), f(r.falseMem_mean), f(destroyedAll(r)), f(r.promptsPer100Turns_mean, 1), r.promptPrecision === "NaN" || r.promptPrecision === "" ? "-" : f(r.promptPrecision)];
  }))), ``);
P(`- With auto-apply, true facts destroyed grow with the error rate (${errors.filter((e) => e > 0).map((e) => f(destroyedAll(err(G, "auto", e)))).join(", ")} per persona at e = ${errors.filter((e) => e > 0).join(", ")}). ` +
  `The gate cuts this to ${errors.filter((e) => e > 0).map((e) => f(destroyedAll(err(G, "gate", e)))).join(", ")}: **${Math.round(100 * Math.min(...red))}-${Math.round(100 * Math.max(...red))}% fewer**.`);
P(`- **F1 hides most of this damage.** F1 counts only the user's own facts; at e = ${e2}, auto-apply destroyed ${f(err(G, "auto", e2).destroyed_mean)} of the user's facts and ${f(err(G, "auto", e2).fillerLost_mean)} background facts per persona, ` +
  `because a wrong change hits whatever true memory the extractor was shown, and most shown memories are background ones. Report destroyed facts as the safety metric and F1 next to it.`);
P(`- The gate does not stop false *new* facts (${f(err(G, "gate", e1).falseMem_mean)} vs ${f(err(G, "auto", e1).falseMem_mean)} at e = ${e1}). Confirming new facts too (gateAll) removes them (${f(err(G, "gateAll", e1).falseMem_mean)}) ` +
  `but costs ${f(n(err(G, "gateAll", e1), "promptsPer100Turns_mean") / n(err(G, "gate", e1), "promptsPer100Turns_mean"), 1)}x the prompts (${f(err(G, "gateAll", e1).promptsPer100Turns_mean, 1)} vs ${f(err(G, "gate", e1).promptsPer100Turns_mean, 1)} per 100 turns).`);
P(`- Append-only never destroys anything but leaves every changed fact stale (${f(err(G, "append", 0).stale_mean)} per persona at e = 0).`, ``);

// Finding 2
const us = gCfg.uSweep;
P(`## Finding 2: the gate depends on a careful user, and a mistaken "keep" is never asked again`, ``);
P(`\`${rel(a.gate)}/\`, user sweep at e = ${gCfg.uSweepError}`, ``);
P(mdTable(["u", "gate F1", "gate stale", "gate wrong changes applied", "gateAll F1", "gateAll wrong changes applied"],
  us.map((u) => { const g = cell(G, "user", "gate", gCfg.uSweepError, u), h = cell(G, "user", "gateAll", gCfg.uSweepError, u); return [u, f(g.f1_mean, 3), f(g.stale_mean), f(g.wrongChangesApplied_mean), f(h.f1_mean, 3), f(h.wrongChangesApplied_mean)]; })), ``);
P(`AURA does not propose a change again after the user turns it down (\`propose()\` in \`server/memory.mjs\`). That avoids nagging, but one mistaken rejection of a correct update keeps the old fact for good: ` +
  `stale facts rise from ${f(cell(G, "user", "gate", gCfg.uSweepError, us[0]).stale_mean)} to ${f(cell(G, "user", "gate", gCfg.uSweepError, us[us.length - 1]).stale_mean)} as u goes from ${us[0]} to ${us[us.length - 1]}. ` +
  `Prompt precision also falls as the extractor gets worse (${f(err(G, "gate", 0).promptPrecision)} at e = 0 to ${f(err(G, "gate", errors[errors.length - 1]).promptPrecision)} at e = ${errors[errors.length - 1]}), so users see more wrong cards exactly when the gate matters most.`, ``);

// Finding 3
const sizes = [...new Set(CH.map((r) => +r.size))].sort((x, y) => x - y);
const chAll = (s) => CH.find((r) => +r.size === s && r.kind === "all");
const big = sizes[sizes.length - 1];
const missRange = sizes.filter((s) => s > 0).map((s) => 1 - n(chAll(s), "reachable"));
const car = CHrows.filter((r) => r.size === 0 && r.slot === "car" && r.kind === "update" && r.phrasing === 0);
P(`## Finding 3: ${pct(Math.min(...missRange))}-${pct(Math.max(...missRange))} of change requests cannot be carried out, because the memory to change is not shown to the extractor`, ``);
P(`\`${rel(a.reach)}/\` (${reachCfg.stores} stores per size, 12 fact types, 3 phrasings per change; 95% Wilson intervals)`, ``);
P(mdTable(["unrelated memories N", "reachable (AURA)", "reachable without the 0.25 minimum"],
  sizes.map((s) => { const r = chAll(s); return [s, `${f(r.reachable, 3)} [${f(r.lo, 3)}, ${f(r.hi, 3)}]`, `${f(r.reachableNoMin, 3)} [${f(r.lo2, 3)}, ${f(r.hi2, 3)}]`]; })), ``);
P(`AURA lets the extractor change only memories shown in its prompt: \`searchMemories(text, 12)\` plus the 8 most recent, and \`searchMemories\` drops everything scoring below 0.25. ` +
  (car.length ? `Even in a store of only 12 memories, search never retrieved the car fact for "${car[0].text.replace(/Nexon|Swift|Creta|Baleno|Seltos/, "<new car>")}" ` +
    `(${car.reduce((t, r) => t + r.viaRelated, 0)} of ${car.length} stores); it was reachable only when it happened to be among the 8 most recent (${car.reduce((t, r) => t + r.reachable, 0)} of ${car.length}). ` : ``) +
  `When the target is missed, the old fact stays active next to the new one. Forget requests are hit hardest (${f(CH.find((r) => +r.size === big && r.kind === "forget").reachable, 3)} at N = ${big}). ` +
  `In Experiment 1 this is the main source of stale facts: ${pct(n(err(G, "gate", 0), "candidateMissRate"))} of change turns missed their target under the gate at e = 0.`, ``);

// Finding 4
const fixRows = [0, e1, e2].flatMap((e) => ["auto", "gate"].map((p) => [e, p]));
P(`## Finding 4: showing the extractor its 12 best matches without a minimum score removes most stale facts`, ``);
P(`\`${rel(a["gate-fix"])}/\` vs. \`${rel(a.gate)}/\` (\`--extract-min-score 0\`)`, ``);
P(mdTable(["e", "policy", "F1 as shipped -> fix", "stale -> fix", "candidate miss rate -> fix", "prompts / 100 -> fix"],
  fixRows.map(([e, p]) => { const x = err(G, p, e), y = err(GF, p, e); return [e, p, `${f(x.f1_mean, 3)} -> ${f(y.f1_mean, 3)}`, `${f(x.stale_mean)} -> ${f(y.stale_mean)}`, `${f(x.candidateMissRate, 3)} -> ${f(y.candidateMissRate, 3)}`, `${f(x.promptsPer100Turns_mean, 1)} -> ${f(y.promptsPer100Turns_mean, 1)}`]; })), ``);
const forgets = mean(gRuns.filter((r) => r.sweep === "error" && r.e === 0).map((r) => r.forgets));
P(`Forget requests whose value is still in a memory row fell from ${f(err(G, "gate", 0).forgetMemResidual_mean)} to ${f(err(GF, "gate", 0).forgetMemResidual_mean)} per persona (gate, e = 0; ${f(forgets)} forget requests per persona). ` +
  `The forgotten value stays in the stored conversation text in every case (${f(err(G, "gate", 0).forgetTextResidual_mean)} of ${f(forgets)}): "forget" deletes the memory, not the transcript it came from. ` +
  `The fix costs more review prompts because changes that used to be impossible now reach the user. It is a one-line change (pass \`{ minScore: 0 }\` from the extractor to \`searchMemories\`) and is **not** on by default.`, ``);

// Finding 5
const thSizes = [...new Set(TH.map((r) => +r.size))].sort((x, y) => x - y);
const ths = [0, 0.15, 0.2, 0.25, 0.3];
const th = (s, t) => TH.find((r) => +r.size === s && +r.threshold === t);
const aura6 = RS.filter((r) => r.variant === "aura_k6");
const auraEmpty = RS.filter((r) => r.variant.startsWith("aura_")).map((r) => +r.emptyRate);
const below = RQ.filter((r) => r.targetHybrid < 0.25).length;
const bigT = thSizes[thSizes.length - 1];
P(`## Finding 5: the fixed minimum score in memory search trades recall for noise, and no single cut-off is good`, ``);
P(`\`${rel(a.retrieval)}/\` (${RQ.length / thSizes.length} questions about stored facts and ${RA.length / thSizes.length} about never-stated ones per store size)`, ``);
P(mdTable(["N", ...ths.map((t) => (t === 0.25 ? "min 0.25 (AURA)" : `min ${t}`))], thSizes.map((s) => [s, ...ths.map((t) => `${f(th(s, t).found, 3)} / ${f(th(s, t).noise, 3)}`)])), ``);
P(`Cells: found (right fact in the top 6) / noise (never-stated questions that still return memories). With AURA's 0.25, ${pct(Math.min(...auraEmpty))}-${pct(Math.max(...auraEmpty))} of questions about a stored fact return **no results at all**, ` +
  `and ${f((100 * below) / RQ.length, 1)}% of right answers score below the cut-off; yet at N = ${bigT}, ${pct(+th(bigT, 0.25).noise)} of questions about things never stated still return unrelated memories. ` +
  `Keyword-only fallback search: hit@6 ${f(RS.find((r) => r.variant === "lexical_k6").hitAtK, 3)}. ` +
  `The re-scoring used for the variants reproduced AURA's real \`searchMemories()\` results in ${RQ.filter((r) => r.sanity).length} of ${RQ.length} queries. ` +
  `This matters once a user has more than 30 memories; the 30 most recent are always in the Live prompt.`, ``);

// Finding 6: real Gemini
P(`## Finding 6: what the real Gemini extractor gets wrong`, ``);
if (!real) {
  P(`Not run yet: \`npm run eval:real -- --yes\`, then \`npm run eval:rescore -- <folder>\` and this script.`, ``);
} else {
  const pols = [...new Set(real.rows.map((r) => r.policy))];
  const s = (rows, k) => rows.reduce((t, r) => t + (+r[k] || 0), 0);
  const realTable = (R0) => mdTable(["policy", "n", "F1", "precision", "recall", "ended", "stale", "false", "hypothetical", "third-party", "true facts destroyed", "prompts / 100 turns", "cards judged right / wrong"],
    [...new Set(R0.map((r) => r.policy))].map((p) => {
      const sel = R0.filter((r) => r.policy === p);
      return [p, sel.length, `${f(mean(sel.map((r) => r.f1)), 3)} ± ${f(ci95(sel.map((r) => r.f1)), 3)}`, f(mean(sel.map((r) => r.precision)), 3), f(mean(sel.map((r) => r.recall)), 3),
        f(mean(sel.map((r) => r.ended))), f(mean(sel.map((r) => r.stale))), f(mean(sel.map((r) => r.false))), f(mean(sel.map((r) => r.hypothetical))), f(mean(sel.map((r) => r.thirdParty))),
        s(sel, "destroyed"), f(mean(sel.map((r) => (100 * r.prompts) / r.userTurns)), 1), `${s(sel, "proposalsJudgedRightDuringRun")} / ${s(sel, "proposalsJudgedWrongDuringRun")}`];
    }));
  P(`\`${rel(real.dir)}/\` (${real.cfg.extractor}; ${real.cfg.personas} personas x ${real.cfg.seeds} seed(s) per policy; u = ${real.cfg.u}; candidate selection ${real.cfg.extractMinScore}; scored with eval/lib/loose.mjs, see rescored.md)`, ``);
  P(realTable(real.rows), ``);
  const req = s(real.rows, "requests");
  const tokIn = s(real.rows, "promptTokens") / req, tokOut = s(real.rows, "outputTokens") / req;
  P(`- Gemini destroyed **${s(real.rows, "destroyed")}** true facts in ${real.rows.length} persona runs (${req} extraction requests, about ${Math.round(tokIn)} input / ${Math.round(tokOut)} output tokens each, mean latency ${f(mean(real.rows.map((r) => r.meanLatencyMs)) / 1000, 1)} s). ` +
    `In these scenarios the destructive errors the gate is built for did not occur; its measured benefit here is therefore nil, and the case for it rests on Finding 1 (it is cheap insurance when they do occur).`);
  const byLabel = (l) => [...new Set(real.labels.filter((x) => x.auto_label === l).map((x) => x.content))];
  P(`- Its errors are of two other kinds. **Stale facts** where the old memory was not shown to it (Finding 3), e.g. ${byLabel("stale").slice(0, 2).map((c) => `"${c}"`).join(", ")}. ` +
    `**New facts that should not have been stored**, which the gate does not review: hypotheticals (${byLabel("hypothetical").map((c) => `"${c}"`).join("; ")})` +
    (byLabel("false").length ? ` and misreadings (${byLabel("false").map((c) => `"${c}"`).join("; ")})` : "") + `.`);
  P(`- It also wrote correct memories in forms a strict checker would miss: facts about people in the user's life (${byLabel("third-party").map((c) => `"${c}"`).filter((v, i, x) => x.indexOf(v) === i).join("; ")}) ` +
    `and retirements written as updates (${byLabel("ended").map((c) => `"${c}"`).join("; ")}). The scoring rules were extended for these after the run (eval/lib/loose.mjs) and re-checked against exact scoring.`);
  const wrong = s(real.rows, "proposalsJudgedWrongDuringRun");
  if (wrong) {
    const logged = jsonl(real.dir, "decisions.jsonl");
    P(logged.length
      ? `- ${wrong} review card(s) were judged wrong during the run (see decisions.jsonl for each card and decision).`
      : `- During the run the simulated user turned down ${wrong} review card(s) it judged wrong with the rules in place at the time. Cards were not logged in this run, so which one is not known; ` +
        `a retirement written as an update (above) would have been turned down, so the gate row may be slightly pessimistic until the run is repeated.`);
  }
  P(``);
  if (realFix) {
    P(`With candidate selection without the minimum score (\`${rel(realFix.dir)}/\`):`, ``);
    P(realTable(realFix.rows), ``);
  }
}

// Checks
